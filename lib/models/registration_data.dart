import 'package:flutter/material.dart';

enum BloomUserType { girl, woman, parent, guestSpeaker, communityPartner }

extension BloomUserTypeX on BloomUserType {
  String get label {
    switch (this) {
      case BloomUserType.girl:
        return 'Girl (Ages 8–17)';
      case BloomUserType.woman:
        return 'Woman (18+)';
      case BloomUserType.parent:
        return 'Parent/Guardian';
      case BloomUserType.guestSpeaker:
        return 'Guest Speaker';
      case BloomUserType.communityPartner:
        return 'Community Partner';
    }
  }

  String get emoji {
    switch (this) {
      case BloomUserType.girl:
        return '👧';
      case BloomUserType.woman:
        return '👩';
      case BloomUserType.parent:
        return '👩‍👧';
      case BloomUserType.guestSpeaker:
        return '🎤';
      case BloomUserType.communityPartner:
        return '🤝';
    }
  }

  IconData get icon {
    switch (this) {
      case BloomUserType.girl:
        return Icons.emoji_people_outlined;
      case BloomUserType.woman:
        return Icons.woman_outlined;
      case BloomUserType.parent:
        return Icons.family_restroom_outlined;
      case BloomUserType.guestSpeaker:
        return Icons.mic_outlined;
      case BloomUserType.communityPartner:
        return Icons.handshake_outlined;
    }
  }
}

/// Holds all state collected across the registration wizard.
class RegistrationData extends ChangeNotifier {
  BloomUserType? userType;

  // Screen 3 — account
  String firstName = '';
  String lastName = '';
  String email = '';
  String password = '';
  String confirmPassword = '';
  bool agreedToPrivacyPolicy = false;

  // Screen 5 — profile
  String? profilePhotoPath;
  String? profilePhotoUrl;
  DateTime? birthday;
  String phoneNumber = '';
  String city = '';
  String state = '';

  // Screen 6 — girls
  String school = '';
  String grade = '';
  final Set<String> girlInterests = {};

  // Screen 6 — women
  String occupation = '';
  bool isBusinessOwner = false;
  final Set<String> womenInterests = {};

  // Screen 6 — parents
  String childName = '';
  String childAge = '';
  String emergencyContact = '';

  /// Optional: a guardian may enter their child's invite code right here
  /// during signup instead of later from Parent Portal. Never required —
  /// linking has no expiry, so there's no rush.
  String guardianInviteCodeInput = '';

  /// Set only for a Girl (minor) account: the invite code generated by
  /// completeMinorSignup, shown to her on the waiting-for-guardian screen
  /// so she can share it.
  String? inviteCode;

  // Screen 6 — guest speakers
  String profession = '';
  String organization = '';
  String speakingTopics = '';
  String availability = '';

  // Community Partner — Step 1: profile
  String partnerBusinessName = '';
  String partnerContactPerson = '';
  String partnerWebsite = '';
  String partnerDescription = '';
  String? partnerLogoUrl;

  // Community Partner — Step 2: how they want to help
  List<String> partnerSupportTypes = [];
  String partnerContributionDetails = '';

  // Community Partner — Step 3: create a Bloom Reward
  String rewardName = '';
  double rewardValue = 0;
  int rewardQuantity = 0;
  int rewardBadgeCost = 1;
  DateTime? rewardExpiration;
  String rewardRestrictions = '';

  // Screen 7
  bool wantsReminders = true;

  void setUserType(BloomUserType type) {
    userType = type;
    notifyListeners();
  }

  void update(VoidCallback mutate) {
    mutate();
    notifyListeners();
  }

  void reset() {
    userType = null;
    firstName = '';
    lastName = '';
    email = '';
    password = '';
    confirmPassword = '';
    agreedToPrivacyPolicy = false;
    profilePhotoPath = null;
    profilePhotoUrl = null;
    birthday = null;
    phoneNumber = '';
    city = '';
    state = '';
    school = '';
    grade = '';
    girlInterests.clear();
    occupation = '';
    isBusinessOwner = false;
    womenInterests.clear();
    childName = '';
    childAge = '';
    emergencyContact = '';
    guardianInviteCodeInput = '';
    inviteCode = null;
    profession = '';
    organization = '';
    speakingTopics = '';
    availability = '';
    partnerBusinessName = '';
    partnerContactPerson = '';
    partnerWebsite = '';
    partnerDescription = '';
    partnerLogoUrl = null;
    partnerSupportTypes = [];
    partnerContributionDetails = '';
    rewardName = '';
    rewardValue = 0;
    rewardQuantity = 0;
    rewardBadgeCost = 1;
    rewardExpiration = null;
    rewardRestrictions = '';
    wantsReminders = true;
    notifyListeners();
  }
}
